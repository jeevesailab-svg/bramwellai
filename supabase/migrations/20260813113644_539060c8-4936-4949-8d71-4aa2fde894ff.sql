$b$## Why filler happens

Um and ah are not verbal tics. They are floor holders. When your brain is still assembling the next clause, filler tells the room "do not interrupt, I am not finished." The behaviour is rational. It is also expensive, because listeners score high filler speech as less prepared and less senior, even when the content is strong.

Research on perceived credibility consistently finds the same thing. The audience is not counting fillers deliberately. They are forming a general impression, and filler drags it down.

## The four step fix

**Step one: measure.** Count fillers per minute across three recorded answers. Under three per minute is fine. Six or more is noticeable. Ten or more is the main thing your listener remembers. Without a number you cannot tell whether you are improving.

**Step two: build the pause tolerance.** Record yourself answering a question with a rule: whenever you feel a filler coming, close your mouth instead. The first attempts will feel unbearably slow. Play them back and you will find the pauses sound far shorter to the listener than they felt to you. That gap between felt time and real time is the whole problem.

**Step three: plan the first sentence.** Most filler clusters at the start of an answer, while you decide what your point is. If you know your opening sentence before you begin, the cluster disappears. Practise starting with a position rather than a preamble.

**Step four: slow the first five words.** Speech speed is set in the opening moments. Start slowly and the whole answer runs at a manageable pace, which gives your thinking time to stay ahead of your mouth.


That is why capable people get overlooked. The thinking is sound. The signal is not.

## The six signals

**Structure.** CEOs answer in a shape. Position first, then two or three supporting points, then the implication. Everyone else narrates their thinking out loud and hopes it arrives somewhere. If your listener cannot predict where you are going after ten seconds, you have lost the room.

**Signal.** This is the ratio of meaning to noise. Filler words, hedges such as "sort of" and "I guess", and long preambles all dilute signal. High signal speech carries information in almost every word.

**Concision.** Senior communicators are short by default and long only on request. The discipline is answering the question asked, then stopping. Silence after a clean answer reads as confidence. Continuing to talk reads as uncertainty.

**Conviction.** Conviction lives in the pitch contour at the end of a sentence. Falling pitch closes a statement. Rising pitch turns it into a question and invites challenge. Most people uptalk under pressure without noticing.

**Authority.** Authority is pace and pause. Rushing signals that you expect to be interrupted. A deliberate pace, with pauses placed before the important word rather than after, signals that you expect to be heard.

**Command edge.** This is the ability to hold a room during disagreement. It shows up as steady volume, no defensive speed up, and the willingness to say "let me be direct" and then be direct.

## How to train each signal

Reading about these does nothing. They are motor patterns, and motor patterns change through repetition with feedback.

Start with structure, because it fixes concision as a side effect. Take any question you are likely to be asked and answer it out loud in this shape: one sentence of position, two sentences of evidence, one sentence of implication. Record it. Play it back. Most people are shocked by how long their preamble is.

Next, work on endings. Record thirty answers and listen only to the final two words of each. Count how many rise. Bringing that to zero is often worth more than any other single change.

Then attack filler. Filler is a symptom of thinking and speaking at the same time. The fix is not to speak faster, it is to pause. A pause replaces "um" and reads as authority rather than hesitation.

